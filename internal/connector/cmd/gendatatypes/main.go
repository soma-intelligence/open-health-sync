// Command gendatatypes reads what each connector's mapper writes from its
// source, and writes it to internal/connector/datatypes_gen.go (what GET
// /v1/providers reports as data_types) and to the generated table of
// docs/connectors/README.md. Nobody keeps the lists by hand, so they cannot
// drift from the mappers; a test fails when the committed copies differ from
// this output.
//
// Run it from the repository root after changing a mapper:
//
//	go run ./internal/connector/cmd/gendatatypes
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	_ "github.com/soma-intelligence/open-health-sync/connectors/all"
	"github.com/soma-intelligence/open-health-sync/internal/connector"
	"github.com/soma-intelligence/open-health-sync/internal/model"
)

const module = "github.com/soma-intelligence/open-health-sync/"

// notEmitted names canonical quantity names that appear in a connector's
// source without being written as a quantity, by slug.
var notEmitted = map[string][]string{
	// The step count of a workout is kept in its metadata.
	"suunto": {model.QTStepCount},
}

// The generated table of docs/connectors/README.md sits between these
// markers.
const (
	startMark = "<!-- data-types:start (generated by go run ./internal/connector/cmd/gendatatypes) -->"
	endMark   = "<!-- data-types:end -->"
)

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	if err := run(*root); err != nil {
		fmt.Fprintln(os.Stderr, "gendatatypes:", err)
		os.Exit(1)
	}
}

func run(root string) error {
	types, err := scanAll(root)
	if err != nil {
		return err
	}
	src, err := goFile(types)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(root, goPath), src, 0o644); err != nil {
		return err
	}
	readme := filepath.Join(root, readmePath)
	doc, err := os.ReadFile(readme)
	if err != nil {
		return err
	}
	doc, err = splice(doc, table(types))
	if err != nil {
		return err
	}
	return os.WriteFile(readme, doc, 0o644)
}

const (
	goPath     = "internal/connector/datatypes_gen.go"
	readmePath = "docs/connectors/README.md"
)

// scanAll lists what every registered connector delivers, by slug: from its
// own DataTypes when it has one, else from its package's source.
func scanAll(root string) (map[string][]string, error) {
	qt, err := QTConstants(filepath.Join(root, "internal/model"))
	if err != nil {
		return nil, err
	}
	canonical := map[string]bool{}
	for name := range model.StorageUnits() {
		canonical[name] = true
	}
	for _, name := range qt {
		canonical[name] = true
	}
	out := map[string][]string{}
	for _, c := range connector.All() {
		if d, ok := c.(connector.DataTypes); ok {
			out[c.Slug()] = d.DataTypes()
			continue
		}
		t := reflect.TypeOf(c)
		for t.Kind() == reflect.Pointer {
			t = t.Elem()
		}
		pkg, ok := strings.CutPrefix(t.PkgPath(), module)
		if !ok {
			return nil, fmt.Errorf("%s: package %s is not in this module", c.Slug(), t.PkgPath())
		}
		r, err := Dir(filepath.Join(root, pkg), canonical, qt)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", c.Slug(), err)
		}
		if len(r.Kinds) == 0 {
			return nil, fmt.Errorf("%s: no MapResult field is filled in %s", c.Slug(), pkg)
		}
		skip := map[string]bool{}
		for _, name := range notEmitted[c.Slug()] {
			skip[name] = true
		}
		list := r.Kinds
		for _, q := range r.Quantities {
			if !skip[q] {
				list = append(list, q)
			}
		}
		out[c.Slug()] = list
	}
	return out, nil
}

// goFile renders internal/connector/datatypes_gen.go.
func goFile(types map[string][]string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// SPDX-License-Identifier: AGPL-3.0-only

// Code generated by go run ./internal/connector/cmd/gendatatypes. DO NOT EDIT.

package connector

// generatedDataTypes is what each connector delivers, by slug, read from
// its mapper's source. DataTypesOf serves it.
var generatedDataTypes = map[string][]string{
`)
	for _, slug := range slugs(types) {
		if c, ok := connector.Get(slug); ok && isExplicit(c) {
			continue // it answers itself
		}
		fmt.Fprintf(&b, "%q: {", slug)
		for i, v := range types[slug] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", v)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// table renders the generated section of docs/connectors/README.md, markers
// included.
func table(types map[string][]string) []byte {
	var b strings.Builder
	b.WriteString(startMark + "\n")
	b.WriteString("| Provider | Record kinds | Quantities |\n|---|---|---|\n")
	kinds := map[string]bool{}
	for _, k := range connector.Kinds {
		kinds[k] = true
	}
	for _, slug := range slugs(types) {
		var ks, qs []string
		for _, v := range types[slug] {
			if kinds[v] {
				ks = append(ks, "`"+v+"`")
			} else {
				qs = append(qs, "`"+v+"`")
			}
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", slug, strings.Join(ks, ", "), strings.Join(qs, ", "))
	}
	b.WriteString(endMark)
	return []byte(b.String())
}

// splice replaces the generated section of doc, markers included.
func splice(doc, section []byte) ([]byte, error) {
	i := bytes.Index(doc, []byte(startMark))
	j := bytes.Index(doc, []byte(endMark))
	if i < 0 || j < i {
		return nil, fmt.Errorf("%s: the generated section markers are missing", readmePath)
	}
	out := append([]byte{}, doc[:i]...)
	out = append(out, section...)
	return append(out, doc[j+len(endMark):]...), nil
}

func isExplicit(c connector.Connector) bool {
	_, ok := c.(connector.DataTypes)
	return ok
}

func slugs(types map[string][]string) []string {
	out := make([]string, 0, len(types))
	for s := range types {
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}
