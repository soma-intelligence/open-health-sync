var updateKEM = flag.Bool("update-kem", false, "rewrite testdata/kem_vectors.json from crypto/mlkem")

const kemVectorsPath = "testdata/kem_vectors.json"

// RFC 7748 section 6.1, typed in from the RFC.
const (
	rfcAlicePriv = "77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a"
	rfcAlicePub  = "8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a"
	rfcBobPriv   = "5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb"
	rfcBobPub    = "de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f"
	rfcShared    = "4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742"
)

// acvpSeed is d || z of NIST ACVP-Server ML-KEM-keyGen-FIPS203 (vsId 42),
// test group 3 (ML-KEM-1024), test case 51. Go's seed form is exactly d || z.
const acvpSeed = "F3A706FAF090C03DB506863AB0B20BD8A1627956318E88C67EB875E8E7266009" +
	"35D2BC43DD1CC879F765BF2A0C5E297889DDE910E57E2BB0EAE417B90AB7A275"

// hybridEncapsRandom is the fixed ML-KEM encapsulation randomness m of the
// hybrid vector.
const hybridEncapsRandom = "4242424242424242424242424242424242424242424242424242424242424242"

type kemVectors struct {
	Comment string `json:"_comment"`
	MLKEM   struct {
		Source string `json:"source"`
		Seed   string `json:"seed"`
		EK     string `json:"ek"`
	} `json:"mlkem1024_keygen"`
	Hybrid struct {
		Comment          string `json:"_comment"`
		MLKEMSeed        string `json:"mlkem_seed"`
		X25519Private    string `json:"x25519_private"`
		EncapsRandom     string `json:"mlkem_encaps_random"`
		EphemeralPrivate string `json:"x25519_ephemeral_private"`
		CTM              string `json:"ct_m"`
		CTX              string `json:"ct_x"`
		K                string `json:"k"`
	} `json:"hybrid"`
}

func unhex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func vectorKeys(t *testing.T, seed, x25519 string) *UserKeys {
	t.Helper()
	k := &UserKeys{Version: 1}
	copy(k.MLKEMSeed[:], unhex(t, seed))
	copy(k.X25519[:], unhex(t, x25519))
	return k
}

func fixedMLKEM(t *testing.T, random string) func(*mlkem.EncapsulationKey1024) ([]byte, []byte, error) {
	return func(ek *mlkem.EncapsulationKey1024) ([]byte, []byte, error) {
		return mlkemtest.Encapsulate1024(ek, unhex(t, random))
	}
}

func writeKEMVectors(t *testing.T) {
	var v kemVectors
	v.Comment = "Generated by go test -run TestKEMVectors -update-kem. mlkem1024_keygen.ek comes " +
		"from crypto/mlkem and was checked equal to the ek of the ACVP case named in source. " +
		"The hybrid vector pins this package's combiner and byte order; it is self-generated."
	v.MLKEM.Source = "NIST ACVP-Server gen-val/json-files/ML-KEM-keyGen-FIPS203/internalProjection.json, vsId 42, tgId 3 (ML-KEM-1024), tcId 51; seed = d || z"
	v.MLKEM.Seed = acvpSeed
	k := vectorKeys(t, acvpSeed, rfcAlicePriv)
	p, err := k.Public()
	if err != nil {
		t.Fatal(err)
	}
	v.MLKEM.EK = hex.EncodeToString(p.MLKEM)

	v.Hybrid.Comment = "Recipient: ML-KEM seed of the ACVP case and the RFC 7748 Alice X25519 key. " +
		"Sender: fixed ML-KEM randomness and the RFC 7748 Bob key as the ephemeral X25519 key."
	v.Hybrid.MLKEMSeed = acvpSeed
	v.Hybrid.X25519Private = rfcAlicePriv
	v.Hybrid.EncapsRandom = hybridEncapsRandom
	v.Hybrid.EphemeralPrivate = rfcBobPriv
	eph, err := ecdh.X25519().NewPrivateKey(unhex(t, rfcBobPriv))
	if err != nil {
		t.Fatal(err)
	}
	key, ctM, ctX, err := encapsulate(p, fixedMLKEM(t, hybridEncapsRandom), eph)
	if err != nil {
		t.Fatal(err)
	}
	v.Hybrid.CTM = hex.EncodeToString(ctM)
	v.Hybrid.CTX = hex.EncodeToString(ctX)
	v.Hybrid.K = hex.EncodeToString(key[:])

	out, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(kemVectorsPath, append(out, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestKEMVectors(t *testing.T) {
	if *updateKEM {
		writeKEMVectors(t)
	}
	raw, err := os.ReadFile(kemVectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	var v kemVectors
	if err := json.Unmarshal(raw, &v); err != nil {
		t.Fatal(err)
	}

	t.Run("mlkem1024 keygen", func(t *testing.T) {
		if !bytes.Equal(unhex(t, v.MLKEM.Seed), unhex(t, acvpSeed)) {
			t.Fatal("vector seed is not the ACVP seed")
		}
		p, err := vectorKeys(t, v.MLKEM.Seed, rfcAlicePriv).Public()
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(p.MLKEM, unhex(t, v.MLKEM.EK)) {
			t.Fatal("encapsulation key differs from the vector")
		}
	})

	t.Run("x25519 rfc7748", func(t *testing.T) {
		alice, err := vectorKeys(t, acvpSeed, rfcAlicePriv).Public()
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(alice.X25519, unhex(t, rfcAlicePub)) {
			t.Fatalf("Alice public %x", alice.X25519)
		}
		bob, err := vectorKeys(t, acvpSeed, rfcBobPriv).Public()
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(bob.X25519, unhex(t, rfcBobPub)) {
			t.Fatalf("Bob public %x", bob.X25519)
		}
		priv, err := ecdh.X25519().NewPrivateKey(unhex(t, rfcAlicePriv))
		if err != nil {
			t.Fatal(err)
		}
		peer, err := ecdh.X25519().NewPublicKey(bob.X25519)
		if err != nil {
			t.Fatal(err)
		}
		ss, err := priv.ECDH(peer)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(ss, unhex(t, rfcShared)) {
			t.Fatalf("shared secret %x", ss)
		}
	})

	t.Run("hybrid", func(t *testing.T) {
		h := v.Hybrid
		k := vectorKeys(t, h.MLKEMSeed, h.X25519Private)
		p, err := k.Public()
		if err != nil {
			t.Fatal(err)
		}
		eph, err := ecdh.X25519().NewPrivateKey(unhex(t, h.EphemeralPrivate))
		if err != nil {
			t.Fatal(err)
		}
		key, ctM, ctX, err := encapsulate(p, fixedMLKEM(t, h.EncapsRandom), eph)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(ctM, unhex(t, h.CTM)) || !bytes.Equal(ctX, unhex(t, h.CTX)) {
			t.Fatal("ciphertexts differ from the vector")
		}
		if !bytes.Equal(key[:], unhex(t, h.K)) {
			t.Fatalf("encapsulated key %x, want %s", key, h.K)
		}
		got, err := k.Decapsulate(unhex(t, h.CTM), unhex(t, h.CTX))
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got[:], unhex(t, h.K)) {
			t.Fatalf("decapsulated key %x, want %s", got, h.K)
		}
	})
}

func TestKEMRoundTrip(t *testing.T) {
	k, err := GenerateUserKeys(1)
	if err != nil {
		t.Fatal(err)
	}
	p, err := k.Public()
	if err != nil {
		t.Fatal(err)
	}
	key, ctM, ctX, err := Encapsulate(p)
	if err != nil {
		t.Fatal(err)
	}
	if len(ctM) != 1568 || len(ctX) != 32 {
		t.Fatalf("ciphertext sizes %d and %d", len(ctM), len(ctX))
	}
	if key == ([32]byte{}) {
		t.Fatal("zero key")
	}
	got, err := k.Decapsulate(ctM, ctX)
	if err != nil {
		t.Fatal(err)
	}
	if got != key {
		t.Fatal("Encapsulate and Decapsulate disagree")
	}
	again, _, _, err := Encapsulate(p)
	if err != nil {
		t.Fatal(err)
	}
	if again == key {
		t.Fatal("two encapsulations gave the same key")
	}
}

func TestKEMOtherUserGetsAnotherKey(t *testing.T) {
	a, err := GenerateUserKeys(1)
	if err != nil {
		t.Fatal(err)
	}
	b, err := GenerateUserKeys(1)
	if err != nil {
		t.Fatal(err)
	}
	p, err := a.Public()
	if err != nil {
		t.Fatal(err)
	}
	key, ctM, ctX, err := Encapsulate(p)
	if err != nil {
		t.Fatal(err)
	}
	// ML-KEM decapsulation does not fail on a foreign ciphertext (implicit
	// rejection); it gives an unrelated key, so the object open fails later.
	got, err := b.Decapsulate(ctM, ctX)
	if err == nil && got == key {
		t.Fatal("another user's keys decapsulated to the same key")
	}
}

func TestKEMTamperedCiphertextGivesAnotherKey(t *testing.T) {
	k, err := GenerateUserKeys(1)
	if err != nil {
		t.Fatal(err)
	}
	p, err := k.Public()
	if err != nil {
		t.Fatal(err)
	}
	key, ctM, ctX, err := Encapsulate(p)
	if err != nil {
		t.Fatal(err)
	}
	m := bytes.Clone(ctM)
	m[0] ^= 1
	if got, err := k.Decapsulate(m, ctX); err == nil && got == key {
		t.Fatal("tampered ct_m gave the same key")
	}
	x := bytes.Clone(ctX)
	x[0] ^= 1
	if got, err := k.Decapsulate(ctM, x); err == nil && got == key {
		t.Fatal("tampered ct_x gave the same key")
	}
}

func TestKEMRejectsBadInput(t *testing.T) {
	k, err := GenerateUserKeys(1)
	if err != nil {
		t.Fatal(err)
	}
	p, err := k.Public()
	if err != nil {
		t.Fatal(err)
	}
	_, ctM, ctX, err := Encapsulate(p)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := k.Decapsulate(ctM[:len(ctM)-1], ctX); err == nil {
		t.Error("short ct_m accepted")
	}
	if _, err := k.Decapsulate(ctM, ctX[:31]); err == nil {
		t.Error("short ct_x accepted")
	}
	// The all-zero X25519 point is low order: the shared secret would be zero.
	if _, err := k.Decapsulate(ctM, make([]byte, 32)); err == nil {
		t.Error("low-order ct_x accepted")
	}
	if _, _, _, err := Encapsulate(PublicKey{MLKEM: p.MLKEM[:100], X25519: p.X25519}); err == nil {
		t.Error("short ML-KEM public key accepted")
	}
	if _, _, _, err := Encapsulate(PublicKey{MLKEM: p.MLKEM, X25519: make([]byte, 32)}); err == nil {
		t.Error("low-order X25519 public key accepted")
	}
}
