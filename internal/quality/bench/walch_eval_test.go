// TestWalchEval scores the Walch nights with the model and calibration
// embedded in the repository, untouched: nothing is fitted on Walch, and it
// refuses to run against a model of another version than ModelVersion. With
// OHS_QUALITY_WRITE=1 it writes docs/quality/walch-eval.md.
func TestWalchEval(t *testing.T) {
	recs, wr, err := LoadWalch(DataDir())
	if errors.Is(err, ErrMissing) {
		t.Skip("Walch is not on disk: extract walch.zip into walch/extracted")
	}
	if err != nil {
		t.Fatal(err)
	}
	sc := quality.NewScorer()
	if sc.Model == nil || sc.Model.Version != ModelVersion {
		t.Fatalf("the embedded model is not the frozen %s", ModelVersion)
	}
	res := &Result{Records: recs, Outcomes: map[string][]Outcome{}}
	for _, v := range Variants {
		res.Outcomes[v] = make([]Outcome, len(recs))
	}
	prior := &quality.Scorer{Priors: sc.Priors}
	for i := range recs {
		res.Outcomes[VariantPrior][i] = outcome(&recs[i], prior)
		res.Outcomes[VariantFull][i] = outcome(&recs[i], sc)
		res.Outcomes[VariantPriorConformal][i] = res.Outcomes[VariantFull][i]
	}
	idx := selectIdx(res, func(*Record) bool { return true })
	b := bootstrap(res, idx, 7)

	var md strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&md, format, a...) }
	w("# Walch et al. 2019: held out evaluation\n\n")
	w("Model `%s`, as embedded, scored on Walch et al. 2019 (PhysioNet sleep-accel 1.0.0, ODC-By 1.0) without any\n", ModelVersion)
	w("fitting on it. Generated by `OHS_QUALITY_WRITE=1 go test -tags bench ./internal/quality/bench -run TestWalchEval -v`.\n\n")
	w("The figure is total sleep per night from a fixed actigraphy rule on the Apple Watch motion (made by the bench:\n")
	w("the release has no sleep figure from Apple and no ECG), against polysomnography. The shipped calibration for\n")
	w("sleep comes from the synthetic source only, so this is a test of the priors more than of anything learned.\n")
	w("Intervals are 95%% bootstraps over nights (one night per person).\n\n%s\n\n", wr.Summary)
	w("| Variant | Nights | Error mean | Error SD | PICP50 | PICP80 | PICP90 | PICP95 | MPIW90 (min) | CRPS (min) | ECE (5 eq.-mass) | Brier |\n")
	w("|---|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, v := range []string{VariantPrior, VariantFull} {
		p := b.Point[v]
		var q []float64
		var hit []bool
		for _, i := range idx {
			q, hit = append(q, res.Outcomes[v][i].Q), append(hit, res.Outcomes[v][i].Hit)
		}
		w("| %s | %d | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", v, p.N, f2(p.MeanErr), f2(p.SDErr),
			withCI(b, v, func(s Stats) float64 { return s.PICP[0] }, 3), withCI(b, v, func(s Stats) float64 { return s.PICP[1] }, 3),
			withCI(b, v, statPICP90, 3), withCI(b, v, func(s Stats) float64 { return s.PICP[3] }, 3),
			f2(p.MPIW90), withCI(b, v, statCRPS, 2), f3(quality.ECEEqualMass(q, hit, 5)), f3(p.Brier))
	}
	t.Log("\n" + md.String())
	if os.Getenv("OHS_QUALITY_WRITE") == "1" {
		write(t, filepath.Join("..", "..", "..", "docs", "quality", "walch-eval.md"), []byte(md.String()))
	}
}
