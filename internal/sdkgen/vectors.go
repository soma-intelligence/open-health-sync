package sdkgen

import (
	"bytes"
	"encoding/base64"
	"encoding/json"
	"errors"
	"strconv"
	"strings"
	"time"

	"github.com/soma-intelligence/open-health-sync/internal/webhook"
)

// vector is one webhook request and whether a receiver must accept it. The
// signing secret is "whsec_" + base64(KeyText): a readable key, so the file
// holds nothing that looks like a credential.
type vector struct {
	Name      string `json:"name"`
	KeyText   string `json:"key_text"`
	ID        string `json:"id"`
	Timestamp string `json:"timestamp"`
	Now       int64  `json:"now"`
	Body      string `json:"body"`
	Signature string `json:"signature"`
	Valid     bool   `json:"valid"`
}

type vectorFile struct {
	Comment string   `json:"comment"`
	Vectors []vector `json:"vectors"`
}

const (
	vectorKey      = "open-health-sync webhook test vector"
	vectorOtherKey = "another endpoint's key"
)

func vectorSecret(keyText string) string {
	return webhook.SecretPrefix + base64.StdEncoding.EncodeToString([]byte(keyText))
}

// WebhookVectors signs a set of requests with internal/webhook and records
// whether its Verify accepts each one. Both SDKs' verification helpers are
// tested against this file, so they agree with the server.
func WebhookVectors() ([]byte, error) {
	ts := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	tsText := strconv.FormatInt(ts.Unix(), 10)
	body := `{"id":"5f0c8e1a-2b7d-4c3e-9a41-0d6b2f8e7c55","type":"data.written","timestamp":"2026-01-01T00:00:00Z",` +
		`"data":{"user_id":"3f0c2f8e-8b8a-4c55-9f5e-2b0f3a1d9c11","external_ref":"customer-42","provider":"withings",` +
		`"records":{"quantity_samples":12},"types":["heart_rate"],"first_day":"2025-12-31","last_day":"2025-12-31"}}`
	id := "5f0c8e1a-2b7d-4c3e-9a41-0d6b2f8e7c55"
	sign := func(keyText, id string, body string) (string, error) {
		return webhook.Sign(vectorSecret(keyText), id, ts, []byte(body))
	}
	good, err := sign(vectorKey, id, body)
	if err != nil {
		return nil, err
	}
	other, err := sign(vectorOtherKey, id, body)
	if err != nil {
		return nil, err
	}
	base := vector{KeyText: vectorKey, ID: id, Timestamp: tsText, Now: ts.Unix() + 10, Body: body, Signature: good}
	with := func(name string, change func(v *vector)) vector {
		v := base
		v.Name = name
		change(&v)
		return v
	}
	tol := int64(webhook.Tolerance / time.Second)
	vs := []vector{
		with("valid", func(v *vector) {}),
		with("valid among several signatures", func(v *vector) { v.Signature = "v1,bm90IHRoaXMgb25l " + good }),
		with("valid at the edge of the tolerance", func(v *vector) { v.Now = ts.Unix() + tol }),
		with("timestamp too old", func(v *vector) { v.Now = ts.Unix() + tol + 1 }),
		with("timestamp in the future", func(v *vector) { v.Now = ts.Unix() - tol - 1 }),
		with("timestamp not a number", func(v *vector) { v.Timestamp = "2026-01-01T00:00:00Z" }),
		with("body changed", func(v *vector) { v.Body = strings.Replace(body, `"quantity_samples":12`, `"quantity_samples":13`, 1) }),
		with("other webhook-id", func(v *vector) { v.ID = "6a1d9f2b-3c8e-4d4f-8b52-1e7c3a9f8d66" }),
		with("signed with another secret", func(v *vector) { v.Signature = other }),
		with("version other than v1", func(v *vector) { v.Signature = "v2," + strings.TrimPrefix(good, "v1,") }),
		with("no signature", func(v *vector) { v.Signature = "" }),
	}
	for i := range vs {
		v := &vs[i]
		err := webhook.Verify(vectorSecret(v.KeyText), v.ID, v.Timestamp, v.Signature, []byte(v.Body), time.Unix(v.Now, 0))
		switch {
		case err == nil:
			v.Valid = true
		case !errors.Is(err, webhook.ErrVerify):
			return nil, err
		}
	}
	f := vectorFile{
		Comment: "Generated by internal/sdkgen with internal/webhook (make sdk). The secret is whsec_ + base64(key_text). " +
			"valid says whether webhook.Verify accepts the request at the Unix time now.",
		Vectors: vs,
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(f); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
